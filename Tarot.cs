        public static TarotCard Card(int id) => Deck.FirstOrDefault(c => c.Id == id);

        // тянет случайную карту из ещё не вытянутых; возвращает null, когда колода пуста
        public static TarotCard Draw(IList<int> drawn, Func<int, int> die = null)
        {
            die = die ?? DiceRoller.Die;
            var left = Deck.Where(c => !drawn.Contains(c.Id)).ToList();
            if (left.Count == 0) return null;
            var card = left[die(left.Count) - 1];
            drawn.Add(card.Id);
            return card;
        }
