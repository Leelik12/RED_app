    public class PunknautPart
    {
        public string Id, Name, Text;
        public int Days, GatherDc, Mod;
        public int Max;                 // сколько раз можно установить (0 — без ограничения)
        public override string ToString() => Name;
    }

    public class PunknautBuild
    {
        public readonly Dictionary<string, int> Count = new Dictionary<string, int>();

        public int Of(string id) => Count.TryGetValue(id, out int n) ? n : 0;
        public void Set(string id, int n) { if (n <= 0) Count.Remove(id); else Count[id] = n; }

        public int Chassis => Of("chassis");
        public int TotalDays => Punknaut.Parts.Sum(p => p.Days * Of(p.Id));
        public int BuildDc => Punknaut.BaseDc + Punknaut.Parts.Sum(p => p.Mod * Of(p.Id));
        public int Hp => 60 + 20 * Chassis;
        public int Seats => 20 + 10 * Chassis;
        public int CombatSpeed => 15 + 5 * Of("av4");
        public int NarrativeKmh => 97 + 32 * Of("av4");
        public int RamBonusD6 => Chassis;                      // +1d6 за каждое дополнительное шасси
        public int SteerSkillOver => 10 + Chassis;             // Сумма навыка вождения выше этого — без проверки
        public int SteerBodyOver => 5 + Chassis;               // ТЕЛ выше этого
        public int SteerPenalty => Chassis;                    // −1 к проверке вождения за шасси
        public int SpikeRamD6 => Of("spikes") == 0 ? 0 : Of("spikes") == 1 ? 2 : 3;   // с NOS при таране

        // нарушения правил сборки
        public List<string> Validate()
        {
            var errors = new List<string>();
            if (Of("base") != 1) errors.Add("Нужна ровно одна основа Панкноута (автобус или грузовик + четыре двигателя AV).");
            foreach (var p in Punknaut.Parts)
                if (p.Max > 0 && Of(p.Id) > p.Max) errors.Add(p.Name + ": не больше " + p.Max + ".");
            if (Of("av4") > Chassis) errors.Add("Дополнительный двигатель AV-4 — по одному на каждое дополнительное шасси.");
            if (Of("turret") > 3 * (1 + Chassis)) errors.Add("Турели: до трёх на основу и до трёх на каждое дополнительное шасси.");
            return errors;
        }
    }

