def build(out):
    P = 'dlc23'
    out.pack(P, 'Нет места лучше дома', 'No Place Like Home')
    e = find(P, 'НЕТ МЕСТА ЛУЧШЕ ДОМА')
    for uid, name, base, mod, multi, mx in UPGRADES:
        ex = {'uid': uid, 'mod': mod, 'cost': '40'}
        if multi:
            ex['multi'] = multi
        if mx:
            ex['max'] = str(mx)
        out.add(P, 'other', name, cost=0, Group=HQ, Info=base, Lib=e['id'], Page=3, Extra=ex)
    for i, text in enumerate(MORAL_TABLE, 1):
        out.add(P, 'other', 'Моральный буст №%d' % i, cost=0, Group=MORAL, Info=text, Lib=e['id'], Page=5, Extra={'n': str(i)})
