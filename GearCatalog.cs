    // каталог оружия, брони и снаряжения из книги (глава «Новая экономика улиц», Ночной рынок)
    public class WeaponDef
    {
        public string Name;          // название типа оружия
        public string Group;         // Холодное / Дальнобойное / Экзотическое
        public string Skill;
        public string Damage;
        public int Mag;              // стандартный магазин (0 — не применимо)
        public string AmmoKind;      // тип боеприпасов
        public int Rof;
        public string Hands;
        public bool Concealable;
        public int Cost;
        public string Alt;           // режимы огня и особенности
        public string Info;          // особые правила экзотики
        public string Poor, Standard, Excellent;   // примеры брендов по качеству
        public int[] Clips;          // стандартный / расширенный / барабан
        public bool FixedQuality;    // экзотика: качество не выбирается
        public string Source = Packs.CoreName;   // книга: «Корник» или название DLC

        public bool IsMelee => Group == "Холодное";
        public bool IsExotic => Group == "Экзотическое";
    }

    public class ArmorDef
    {
        public string Name;
        public int SP;               // для щита — ПЗ
        public int Penalty;          // штраф к РЕА, ЛВК и СКО (положительное число)
        public int Cost;
        public bool IsShield;
        public bool IsSuit;          // костюм Bodyweight: голова и тело сразу
        public string Info;
        public string Source = Packs.CoreName;
    }

    public class GearDef
    {
        public string Name;
        public string Group;         // Снаряжение / Боеприпасы / Приспособления
        public int Cost;
        public string Info;
        public string Source = Packs.CoreName;
    }

    public static class GearCatalog
    {
        public static string CostText(int cost)
        {
            string cat;
            switch (cost)
            {
                case 10: cat = "Дёшево"; break;
                case 20: cat = "Повседневно"; break;
                case 50: cat = "Недёшево"; break;
                case 100: cat = "Премиум"; break;
                case 500: cat = "Дорого"; break;
                case 1000: cat = "Очень дорого"; break;
                case 5000: cat = "Роскошь"; break;
                case 10000: cat = "Супер-роскошь"; break;
                default: cat = null; break;
            }
            string num = cost >= 1000 ? (cost / 1000) + " " + (cost % 1000).ToString("D3") : cost.ToString();
            return cat == null ? num + "eb" : num + "eb (" + cat + ")";
        }

        // стоимость по качеству (таблица «Оружие отличного и низкого качества»)
        public static int PoorCost(int baseCost) { switch (baseCost) { case 50: return 20; case 100: return 50; case 500: return 100; default: return baseCost; } }
        public static int ExcellentCost(int baseCost) { switch (baseCost) { case 50: return 100; case 100: return 500; case 500: return 1000; default: return baseCost; } }

        public const int ExtendedMagCost = 100;   // расширенный магазин
        public const int DrumMagCost = 500;       // барабанный магазин

        private static WeaponDef Melee(string name, string dmg, int rof, bool conceal, int cost, string example)
            => new WeaponDef { Name = name, Group = "Холодное", Skill = "Оружие ближнего боя", Damage = dmg, Rof = rof, Hands = "зависит от типа", Concealable = conceal, Cost = cost, Info = "", Poor = "", Standard = example, Excellent = "" };

        private static WeaponDef Ranged(string name, string skill, string dmg, int mag, string ammo, int rof, int hands, bool conceal, int cost, string alt,
            string poor, string std, string exc, int ext, int drum)
            => new WeaponDef
            {
                Name = name, Group = "Дальнобойное", Skill = skill, Damage = dmg, Mag = mag, AmmoKind = ammo, Rof = rof, Hands = hands.ToString(),
                Concealable = conceal, Cost = cost, Alt = alt, Poor = poor, Standard = std, Excellent = exc,
                Clips = mag > 0 && ext > 0 ? new[] { mag, ext, drum } : null
            };

        private static WeaponDef Exotic(string name, string skill, string dmg, int mag, string ammo, int rof, int hands, int cost, string info)
            => new WeaponDef
            {
                Name = name, Group = "Экзотическое", Skill = skill, Damage = dmg, Mag = mag, AmmoKind = ammo, Rof = rof, Hands = hands.ToString(),
                Concealable = false, Cost = cost, Info = info, FixedQuality = true
            };

